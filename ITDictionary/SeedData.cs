        public static void Run()
        {
            var existing = Database.Terms
                .Find(FilterDefinition<Term>.Empty)
                .Project(t => t.Word)
                .ToList()
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            var missing = Terms.Where(t => !existing.Contains(t.Word)).ToList();
            if (missing.Count > 0)
                Database.Terms.InsertMany(missing);
        }
